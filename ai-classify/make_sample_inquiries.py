# カテゴリごとの目標件数（合計100件）
QUOTA = {
    "配送遅延": 13,
    "返品・交換": 10,
    "不良品": 10,
    "請求・領収書": 8,
    "使い方の質問": 10,
    "予約変更": 8,
    "クレーム": 8,
    "感謝・好意的な感想": 8,
    "営業・売り込み": 6,
    "採用問い合わせ": 6,
    "その他": 7,
}
assert sum(QUOTA.values()) + len(AMBIGUOUS) == 100, sum(QUOTA.values()) + len(AMBIGUOUS)


def fill(t):
    return t.format(p=random.choice(PRODUCTS), o=order_no())


def build_rows():
    rows = []
    for cat, quota in QUOTA.items():
        templates = TEMPLATES[cat]
        picks = []
        # テンプレートを必要数だけ重複少なめに選ぶ（テンプレ数 < quota の場合は許容して繰り返す）
        pool = templates.copy()
        random.shuffle(pool)
        while len(picks) < quota:
            if not pool:
                pool = templates.copy()
                random.shuffle(pool)
            picks.append(pool.pop())
        for t in picks:
            text = fill(t)
            rows.append((cat, text))

    for cat, text in AMBIGUOUS:
        rows.append((cat, fill(text) if "{p}" in text or "{o}" in text else text))

    random.shuffle(rows)
    return rows


def main():
    rows = build_rows()
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["日時", "顧客名(架空)", "問い合わせ本文"])
        for _cat, text in rows:
            w.writerow([rand_datetime(), cust_name(), text])

    lens = [len(t) for _c, t in rows]
    print(f"Wrote {len(rows)} rows to {OUT_PATH}")
    print(f"text length min/avg/max = {min(lens)}/{sum(lens)//len(lens)}/{max(lens)}")


if __name__ == "__main__":
    main()
