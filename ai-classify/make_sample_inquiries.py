def rand_datetime(day_from=(2026, 7, 1), day_to=(2026, 9, 9)):
    import datetime
    d1 = datetime.date(*day_from)
    d2 = datetime.date(*day_to)
    delta = (d2 - d1).days
    d = d1 + datetime.timedelta(days=random.randint(0, delta))
    h = random.randint(8, 22)
    m = random.choice([0, 5, 10, 15, 20, 25, 30, 35, 40, 45, 50, 55])
    return f"{d.strftime('%Y-%m-%d')} {h:02d}:{m:02d}"


